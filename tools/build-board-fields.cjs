/* Question fields use the same 19-field source as the home/search UI. */
const fs=require('fs'),assert=require('assert'),path=require('path');
const root=path.resolve(__dirname,'..'),read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const catalog=read('data/work-catalog.json'),services=read('data/service-fields.json');
const fields=services.map(f=>({id:f.value,name:f.label,works:catalog.tasks.filter(t=>t.expertCategory===f.value||(f.id==='bath'&&t.fieldId==='bath')).map(t=>t.id)}));
const legacy=[...catalog.groups.map(g=>({id:g.id,name:g.name})),{id:'unknown',name:'분야를 모르겠어요'}];
assert.equal(new Set(fields.map(f=>f.id)).size,services.length);
for(const f of fields){assert(f.works.length);assert(f.id.length<=20);}
const data={fields,legacy};
fs.writeFileSync(path.join(root,'board-fields.js'),'/* GENERATED by tools/build-board-fields.cjs */\nwindow.YESSURI_BOARD_FIELDS='+JSON.stringify(data)+';\n');
fs.writeFileSync(path.join(root,'supabase/functions/board-api/fields.json'),JSON.stringify(data)+'\n');
fs.writeFileSync(path.join(root,'supabase/functions/board-api/catalog.json'),JSON.stringify(catalog.tasks.map(t=>({id:t.id,group_id:catalog.fields.find(f=>f.id===t.fieldId).groupId})))+'\n');
console.log(fields.length+' question fields and '+catalog.tasks.length+' legacy work mappings generated');
